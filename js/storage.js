/**
 * Storage & Exporter
 * LocalStorage persistence and Markdown/Print document exporter.
 */

const STORAGE_KEY_PROFILE = "carrier_path_user_profile";
const STORAGE_KEY_CONSULTATION = "carrier_path_consultation";

export function saveToStorage(profile, consultation) {
  try {
    localStorage.setItem(STORAGE_KEY_PROFILE, JSON.stringify(profile));
    localStorage.setItem(STORAGE_KEY_CONSULTATION, JSON.stringify(consultation));
  } catch (err) {
    console.warn("Unable to save to localStorage:", err);
  }
}

export function loadFromStorage() {
  try {
    const profile = localStorage.getItem(STORAGE_KEY_PROFILE);
    const consultation = localStorage.getItem(STORAGE_KEY_CONSULTATION);
    return {
      profile: profile ? JSON.parse(profile) : null,
      consultation: consultation ? JSON.parse(consultation) : null
    };
  } catch (err) {
    console.warn("Unable to read from localStorage:", err);
    return { profile: null, consultation: null };
  }
}

export function exportRoadmapToMarkdown(consultation, profile) {
  if (!consultation) return;

  const md = `# Carrier-Path Strategic Trajectory: ${consultation.careerTitle}
Generated by **Gravity** (AI Career Counselor) on ${new Date().toLocaleDateString()}

---

## 1. Assessment & Profile Diagnostics
${consultation.assessment.replace(/\*\*/g, '')}

- **Target Career Domain**: ${consultation.careerTitle} (${consultation.category})
- **Market Demand**: ${consultation.marketDemand}
- **Weekly Commitment**: ${profile.weeklyHours || 15} hours/week
- **Budget Tier**: ${profile.budget || "Standard"}

---

## 2. Recommended Strategic Options
${consultation.recommendedPaths.map((p, i) => `### Option 0${i + 1}: ${p.title}
- **Why It Fits**: ${p.fit}
- **Market Outlook**: ${p.marketOutlook}
`).join("\n")}

---

## 3. Actionable 3-Phase Roadmap

### Phase 1: ${consultation.roadmap.shortTerm.title} (${consultation.roadmap.shortTerm.period})
**Objective**: ${consultation.roadmap.shortTerm.objective}
${consultation.roadmap.shortTerm.certification ? `**Recommended Certification**: ${consultation.roadmap.shortTerm.certification}\n` : ''}

**Milestones:**
${consultation.roadmap.shortTerm.milestones.map(m => `- [${m.completed ? 'x' : ' '}] ${m.text}`).join("\n")}

${consultation.roadmap.shortTerm.projectIdea ? `**Key Portfolio Blueprint:**
- **Title**: ${consultation.roadmap.shortTerm.projectIdea.title}
- **Tech Stack**: ${consultation.roadmap.shortTerm.projectIdea.stack}
- **Deliverables**: ${consultation.roadmap.shortTerm.projectIdea.description}
` : ''}

---

### Phase 2: ${consultation.roadmap.mediumTerm.title} (${consultation.roadmap.mediumTerm.period})
**Objective**: ${consultation.roadmap.mediumTerm.objective}
${consultation.roadmap.mediumTerm.certification ? `**Recommended Certification**: ${consultation.roadmap.mediumTerm.certification}\n` : ''}

**Milestones:**
${consultation.roadmap.mediumTerm.milestones.map(m => `- [${m.completed ? 'x' : ' '}] ${m.text}`).join("\n")}

${consultation.roadmap.mediumTerm.projectIdea ? `**Key Portfolio Blueprint:**
- **Title**: ${consultation.roadmap.mediumTerm.projectIdea.title}
- **Tech Stack**: ${consultation.roadmap.mediumTerm.projectIdea.stack}
- **Deliverables**: ${consultation.roadmap.mediumTerm.projectIdea.description}
` : ''}

---

### Phase 3: ${consultation.roadmap.longTerm.title} (${consultation.roadmap.longTerm.period})
**Objective**: ${consultation.roadmap.longTerm.objective}

**Milestones:**
${consultation.roadmap.longTerm.milestones.map(m => `- [${m.completed ? 'x' : ' '}] ${m.text}`).join("\n")}

${consultation.roadmap.longTerm.strategy ? `**Tactical Hiring Strategy**: ${consultation.roadmap.longTerm.strategy}\n` : ''}

---

## 4. Next Step Alignment
> **Gravity's Question**: "${consultation.clarifyingQuestion}"

---
*Generated via Carrier-Path &bull; Precision Step-by-Step AI Career Intelligence*
`;

  const blob = new Blob([md], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `CarrierPath-${consultation.careerTitle.replace(/[^a-zA-Z0-9]/g, "_")}-Roadmap.md`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
